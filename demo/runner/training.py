"""Training-side helpers. Reuse, do not reimplement: identity guard (training_result.validate_config),
gate decision (training.gate.passes_gate) and auto fingerprint (auto_mlops.fingerprint)."""
from __future__ import annotations

import contextlib
import importlib.util
import json
import os
import re
from pathlib import Path
from typing import Any

import yaml

from demo.runner.spec import ROOT

BASE_CONFIG = ROOT / "configs/training.yaml"
HEADER = ("# Generated by `python -m demo.runner render-configs` from configs/training.yaml + preset model overrides.\n"
          "# Evaluation identity (dataset, splits, seed, sampling, gate) is unchanged. Do not edit by hand.\n")
IDENTITY_FIELDS = ("seed", "periods", "sample_limit_per_month", "duration_min_minutes", "duration_max_minutes",
                   "source_base_url")


def _script(name: str):
    spec = importlib.util.spec_from_file_location(f"demo_{name}", ROOT / "scripts" / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@contextlib.contextmanager
def _in_root():
    previous = Path.cwd()
    os.chdir(ROOT)
    try:
        yield
    finally:
        os.chdir(previous)


def _format(value: Any) -> str:
    return yaml.safe_dump(value, default_flow_style=True).strip().removesuffix("...").strip()


def patch_model_block(text: str, overrides: dict[str, Any]) -> str:
    """Change only `model:` values, line by line, so the Git diff shows exactly the tuned parameters."""
    lines = text.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.rstrip() == "model:")
    except StopIteration as error:
        raise ValueError("Base config has no top-level model block") from error
    end = next((i for i in range(start + 1, len(lines)) if lines[i] and not lines[i].startswith(" ")), len(lines))
    pending = dict(overrides)
    for i in range(start + 1, end):
        match = re.fullmatch(r"(\s+)([A-Za-z_]+):\s*(.*)", lines[i])
        if match and match.group(2) in pending:
            lines[i] = f"{match.group(1)}{match.group(2)}: {_format(pending.pop(match.group(2)))}"
    insert = [f"  {key}: {_format(value)}" for key, value in pending.items()]
    lines[end:end] = insert
    result = "\n".join(lines) + "\n"
    loaded = yaml.safe_load(result)
    if any(loaded["model"][key] != value for key, value in overrides.items()):
        raise ValueError("Model patch did not round-trip")
    return result


def render_demo_config(overrides: dict[str, Any], base: Path = BASE_CONFIG) -> str:
    return HEADER + patch_model_block(base.read_text(encoding="utf-8"), overrides)


def validate_identity(path: Path) -> None:
    """Exactly the check train_workflow.sh runs in the cloud before building the image."""
    with _in_root():
        _script("training_result").validate_config(Path(path).resolve().relative_to(ROOT))


def semantic_match(config_text: str, base_text: str, overrides: dict[str, Any]) -> list[str]:
    """Differences between a committed demo config and (base identity + overrides)."""
    config, base = yaml.safe_load(config_text), yaml.safe_load(base_text)
    problems = [f"identity field {key} differs" for key in IDENTITY_FIELDS if config.get(key) != base.get(key)]
    problems += [f"model.{key}={config['model'].get(key)!r} != {value!r}"
                 for key, value in overrides.items() if config["model"].get(key) != value]
    return problems


def in_auto_fingerprint(path: str) -> bool:
    return bool(_script("auto_mlops").training_path(path))


def fingerprint_at(sh, ref: str) -> str | None:
    result = sh.run(["git", "rev-parse", ref], timeout=30)
    if not result.ok:
        return None
    with _in_root():
        return _script("auto_mlops").fingerprint(result.stdout.strip())


def gate_fraction() -> float:
    return float(yaml.safe_load((ROOT / "configs/mlflow.yaml").read_text())["minimum_mae_improvement_fraction"])


def preview_decision(candidate_mae: float, reference_mae: float, fraction: float | None = None,
                     reference: str = "champion") -> dict[str, Any]:
    """Offline mirror of the cloud gate: same function, same threshold; never registers anything."""
    from training.gate import Reference, passes_gate
    fraction = gate_fraction() if fraction is None else fraction
    passed = passes_gate(candidate_mae, Reference(reference, reference_mae), fraction)
    threshold = reference_mae * (1 - fraction)
    return {"decision": "approved" if passed else "rejected", "candidate_validation_mae": candidate_mae,
            "reference_validation_mae": reference_mae, "reference": reference, "required_max_mae": threshold,
            "margin_minutes": threshold - candidate_mae,
            "improvement_percent": 100 * (reference_mae - candidate_mae) / reference_mae}


def read_run(run_dir: Path) -> dict[str, Any]:
    from training.gate import validation_dataset_key
    manifest = json.loads((run_dir / "manifest.json").read_text())
    metrics = json.loads((run_dir / "metrics.json").read_text())
    schema = json.loads((run_dir / "feature_schema.json").read_text())
    return {"run_dir": str(run_dir), "validation_mae": metrics["validation"]["model"]["mae_minutes"],
            "test_mae": metrics["test"]["model"]["mae_minutes"],
            "validation_dataset_key": validation_dataset_key(manifest, schema),
            "model": manifest["configuration"]["model"]}


def latest_run(parent: Path) -> Path | None:
    runs = sorted(p for p in parent.glob("*") if (p / "metrics.json").is_file())
    return runs[-1] if runs else None
